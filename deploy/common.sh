# Shared by deploy/hub/init.sh and deploy/remote/init.sh (sourced, not run). Host-specific values
# only ever go into the gitignored files these helpers write.

shopt -u patsub_replacement 2>/dev/null || true # keep "&" literal in ${var//x/y} (bash 5.2)

die() {
  echo "$*" >&2
  exit 2
}

# Reads a setting remembered in .env by an earlier run.
setting() {
  [[ -f .env ]] && sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" .env | tail -1
  return 0
}

check_name() {
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9\ ._()-]*$ ]] ||
    die 'Pass --name "<server name>" (letters, digits, spaces and . _ ( ) -); it must match the dashboard config.'
}

check_disks() {
  local d
  for d in "$@"; do
    [[ "$d" =~ ^/[A-Za-z0-9/._-]+$ && -d "$d" ]] || die "--data-disk $d: not an existing absolute directory"
  done
}

json_list() {
  local out="" d
  for d in "$@"; do out+="${out:+, }\"$d\""; done
  printf '[%s]' "$out"
}

# Copies a template, replacing __KEY__ placeholders: fill <template> <output> KEY=value ...
fill() {
  local text pair
  text="$(<"$1")"
  for pair in "${@:3}"; do text="${text//__${pair%%=*}__/${pair#*=}}"; done
  printf '%s\n' "$text" >"$2"
}

# exporter.config.json for this host: its data disks (none: no disk is reported) and options.
write_exporter_config() { # <unifiedMemoryFallback true|false> <disk>...
  local unified="$1" disks
  shift
  disks="$(json_list "$@")"
  cat >exporter.config.json <<EOF
{
  "listenHost": "127.0.0.1",
  "listenPort": 19101,
  "diskMountPrefixes": $disks,
  "diskTopFolderMountPrefixes": $disks,
  "dockerHost": "unix:///run/docker-proxy/proxy.sock",
  "unifiedMemoryFallback": $unified
}
EOF
}

# compose.override.yaml for this host: data disks (read-only, each at its own path, plus the
# capability du needs) and, when installed, the host's own DCGM client so it always matches the
# host engine's version.
write_compose_override() { # <disk>...
  local volumes=() d dcgmi lib
  for d in "$@"; do volumes+=("$d:$d:ro,rslave"); done
  if dcgmi="$(command -v dcgmi)" && lib="$(ldconfig -p 2>/dev/null | awk '/libdcgm\.so\.4 /{print $NF; exit}')" && [[ -n "$lib" ]]; then
    volumes+=("$dcgmi:/usr/bin/dcgmi:ro" "$lib:$lib:ro")
  fi
  {
    echo "# Generated by init.sh for this host."
    if ((${#volumes[@]} == 0)); then
      echo "services: {}"
      return
    fi
    echo "services:"
    echo "  exporter:"
    (($#)) && echo "    cap_add: [DAC_READ_SEARCH] # du reads every directory of the data disks"
    echo "    volumes:"
    for d in "${volumes[@]}"; do echo "      - $d"; done
  } >compose.override.yaml
}
