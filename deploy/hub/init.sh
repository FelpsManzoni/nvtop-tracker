#!/usr/bin/env bash
# Prepares this directory for `docker compose up -d --build` on the hub: the host running the
# team's Prometheus, the dashboard and its own exporter. Host-specific values only go into
# gitignored files: .env (UID/GID, settings, Prometheus credentials), web.yml (bcrypt hash),
# prometheus.yml, exporter.config.json and compose.override.yaml. Settings are remembered in .env,
# so re-running needs no options; --new-password rotates the Prometheus password (then update
# each remote host's prometheus-password and restart its stack).
#
#   ./init.sh --name "GPU Server 1" [--data-disk /data/disk1 ...] [--new-password]
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
source ../common.sh

NAME="" DISKS=() NEW_PASSWORD=0
while (($#)); do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --data-disk) DISKS+=("$2"); shift 2 ;;
    --new-password) NEW_PASSWORD=1; shift ;;
    *) die "unknown option: $1" ;;
  esac
done
[[ -n "$NAME" ]] || NAME="$(setting NVTOP_SERVER_NAME)"
((${#DISKS[@]})) || read -ra DISKS <<<"$(setting NVTOP_DATA_DISKS)"
check_name "$NAME"
check_disks "${DISKS[@]}"
PASSWORD=""
((NEW_PASSWORD)) || PASSWORD="$(setting PROMETHEUS_PASSWORD)"
[[ -n "$PASSWORD" ]] || PASSWORD="$(head -c 32 /dev/urandom | base64 | tr -d '/+=' | head -c 32)"

mkdir -p data avatars prometheus-data
[[ -f config.json ]] || echo "config.json missing: cp config.example.json config.json, then edit it." >&2

fill prometheus.example.yml prometheus.yml "SERVER_NAME=$NAME"
write_exporter_config false "${DISKS[@]}"
write_compose_override "${DISKS[@]}"

umask 077
cat >.env <<EOF
NVTOP_UID=$(id -u)
NVTOP_GID=$(id -g)
NVTOP_SERVER_NAME="$NAME"
NVTOP_DATA_DISKS="${DISKS[*]}"
PROMETHEUS_USERNAME=nvtop
PROMETHEUS_PASSWORD=$PASSWORD
EOF
# htpasswd reads the password from stdin, so it never shows up in a process list.
HASH="$(printf '%s\n' "$PASSWORD" | docker run --rm -i httpd:2.4.68-alpine htpasswd -niBC 10 nvtop | cut -d: -f2)"
cat >web.yml <<EOF
# Generated by init.sh: Prometheus basic auth (user nvtop; the password is in .env).
basic_auth_users:
  nvtop: $HASH
EOF

echo "Ready: docker compose up -d --build. Remote hosts need PROMETHEUS_PASSWORD from $(pwd)/.env."
